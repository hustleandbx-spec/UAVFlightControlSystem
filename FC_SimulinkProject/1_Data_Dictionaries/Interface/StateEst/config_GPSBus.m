function cfg = config_GPSBus()
%CONFIG_GPSBUS 契约 #7：GPS/RTK 测量帧（含有效性、质量与采样时间戳）。
% 供 StateEstimation 消费（GPS 中速直连，DEC-072/074；RTK 定位+定向测量输入，DEC-105）。
%
% 质量字段语义（DOP 方案 L1）：
%   FixType 采用 MAVLink GPS_FIX_TYPE 取值（...5=RTK_FLOAT, 6=RTK_FIXED），复用既有外部协议枚举。
%   Eph/Epv 由传感器模型按 DOP 误差预算派生上报，供估计器时变 R 使用；
%   它们不是常量配置，而随 HDOP/VDOP/FixType 变化。
% Valid = 帧完整性（非质量等级）；质量由 FixType/Eph/Epv 表达。

cfg.busName = 'GPSBus';
cfg.contractDomain = 'StateEst';
cfg.description = 'GPS/RTK 测量帧（含有效性、质量与采样时间戳）';
cfg.elements = { ...
    'Lat',         'single',  1, 'deg', '纬度'; ...
    'Lon',         'single',  1, 'deg', '经度'; ...
    'Alt',         'single',  1, 'm',   '海拔（WGS84 椭球高）'; ...
    'Velocity',    'single',  3, 'm/s', 'NED 速度'; ...
    'FixType',     'uint8',   1, '',    '定位类型（MAVLink GPS_FIX_TYPE）'; ...
    'NumSat',      'uint8',   1, '',    '参与解算卫星数'; ...
    'Eph',         'single',  1, 'm',   '水平定位不确定度(1σ)，由 DOP 预算派生'; ...
    'Epv',         'single',  1, 'm',   '垂直定位不确定度(1σ)，由 DOP 预算派生'; ...
    'Sequence',    'uint32',  1, '',    '测量帧序号'; ...
    'Timestamp',   'double',  1, 's',   '测量采样时间戳'; ...
    'IsNew',       'boolean', 1, '',    'GPS 消息为新帧'; ...
    'Valid',       'boolean', 1, '',    '测量帧有效标志（帧完整性，非质量等级）'; ...
    };
end
